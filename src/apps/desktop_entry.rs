use std::fs::{self, OpenOptions};
use std::path::PathBuf;
use xxhash_rust::xxh64::xxh64;

fn applications_dir() -> Result<PathBuf, String> {
    let dir = crate::paths::applications_dir();
    fs::create_dir_all(&dir)
        .map_err(|e| format!("Failed to create applications dir {}: {}", dir.display(), e))?;
    Ok(dir)
}

fn sanitize_app_name_for_filename(name: &str) -> String {
    let mut safe_name = String::new();
    let mut last_was_dash = false;

    for ch in name.trim().chars() {
        let normalized = if ch.is_alphanumeric() || matches!(ch, '-' | '_' | '.') {
            let mut lower = ch.to_lowercase().collect::<String>();
            if lower.is_empty() {
                None
            } else {
                if lower.chars().count() > 1 {
                    lower = lower
                        .chars()
                        .filter(|c| c.is_alphanumeric() || matches!(c, '-' | '_' | '.'))
                        .collect();
                }
                if lower.is_empty() {
                    None
                } else {
                    Some(lower)
                }
            }
        } else if ch.is_whitespace() || matches!(ch, '/' | '\\') {
            Some("-".to_string())
        } else {
            Some("-".to_string())
        };

        if let Some(part) = normalized {
            if part == "-" {
                if !safe_name.is_empty() && !last_was_dash {
                    safe_name.push('-');
                }
                last_was_dash = true;
            } else {
                safe_name.push_str(&part);
                last_was_dash = false;
            }
        }
    }

    let safe_name = safe_name.trim_matches('-');
    if safe_name.is_empty() {
        "app".to_string()
    } else {
        safe_name.to_string()
    }
}

fn stable_name_suffix(name: &str) -> String {
    format!("{:08x}", xxh64(name.as_bytes(), 0))
}

fn desktop_file_path(name: &str) -> Result<PathBuf, String> {
    let safe_name = sanitize_app_name_for_filename(name);
    let suffix = stable_name_suffix(name);
    Ok(applications_dir()?.join(format!("{}-{}.desktop", safe_name, suffix)))
}

fn validate_desktop_field(label: &str, value: &str) -> Result<(), String> {
    if value.contains(['\n', '\r', '\0']) {
        return Err(format!(
            "Invalid {}: embedded newline or NUL is not allowed",
            label
        ));
    }
    Ok(())
}

fn desktop_entry_content(name: &str, exec_command: &str) -> String {
    format!(
        "# Generated by iVnc\n[Desktop Entry]\nVersion=1.0\nType=Application\nName={}\nExec={}\nTerminal=false\nCategories=Utility;\n",
        name, exec_command,
    )
}

pub fn ensure_desktop_entry(name: &str, exec_command: &str) -> Result<PathBuf, String> {
    validate_desktop_field("Name", name)?;
    validate_desktop_field("Exec", exec_command)?;

    let path = desktop_file_path(name)?;
    write_entry(path, name, exec_command)
}

/// The old built-in entry contained shell assignments directly in Exec and
/// could remove live Chrome singleton locks. Retire only the exact known
/// generated entry, after its replacement has been written successfully.
pub fn retire_legacy_chrome_entry() -> Result<(), String> {
    let path = desktop_file_path("Chrome")?;
    if fs::symlink_metadata(&path).is_ok_and(|m| m.is_file())
        && fs::read_to_string(&path).is_ok_and(|s| known_legacy_chrome_entry(&s))
    {
        fs::remove_file(path).map_err(|e| e.to_string())?;
    }
    Ok(())
}

fn known_legacy_chrome_entry(content: &str) -> bool {
    let Some(command) = content.lines().find_map(|line| line.strip_prefix("Exec=")) else {
        return false;
    };
    let Some((config, _)) = super::chrome::legacy_config(command, None) else {
        return false;
    };
    content == desktop_entry_content("Chrome", command)
        && config.profile_dir.as_deref() == crate::paths::chrome_profile().to_str()
        && config.crash_dir.as_deref() == crate::paths::chrome_crash_dumps_dir().to_str()
}

fn write_entry(path: PathBuf, name: &str, exec_command: &str) -> Result<PathBuf, String> {
    let content = desktop_entry_content(name, exec_command);
    if fs::read_to_string(&path).ok().as_deref() == Some(content.as_str()) {
        return Ok(path);
    }
    let temp = path.with_extension(format!("desktop.tmp-{}", uuid::Uuid::new_v4()));
    use std::os::unix::fs::OpenOptionsExt;
    let result = (|| -> Result<(), String> {
        use std::io::Write;
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o644)
            .open(&temp)
            .map_err(|e| e.to_string())?;
        file.write_all(content.as_bytes())
            .map_err(|e| e.to_string())?;
        fs::rename(&temp, &path).map_err(|e| e.to_string())?;
        Ok(())
    })();
    let _ = fs::remove_file(&temp);
    result?;
    Ok(path)
}

/// Desktop Exec does not interpret shell assignments/semicolons. A per-app
/// script also gives identically named Chrome apps independent launch entries.
pub fn ensure_app_entry(app: &super::app::ManagedApp) -> Result<PathBuf, String> {
    ensure_app_entry_in(app, None)
}

#[cfg(test)]
pub fn ensure_app_entry_for_test(
    app: &super::app::ManagedApp,
    root: &std::path::Path,
) -> Result<PathBuf, String> {
    ensure_app_entry_in(app, Some(root))
}

fn ensure_app_entry_in(
    app: &super::app::ManagedApp,
    base: Option<&std::path::Path>,
) -> Result<PathBuf, String> {
    let command = app
        .exec_command
        .as_deref()
        .ok_or("Missing desktop command")?;
    if app.chrome.is_none() {
        if let Some(base) = base {
            fs::create_dir_all(base).map_err(|e| e.to_string())?;
            validate_desktop_field("Name", &app.name)?;
            validate_desktop_field("Exec", command)?;
            return write_entry(base.join(format!("{}.desktop", app.id)), &app.name, command);
        }
        return ensure_desktop_entry(&app.name, command);
    }
    validate_desktop_field("Name", &app.name)?;
    let root = base
        .map(|p| p.join(&app.id))
        .unwrap_or_else(|| crate::paths::app_dir(&app.id));
    fs::create_dir_all(&root).map_err(|e| e.to_string())?;
    let script = root.join("launch-chrome.sh");
    let temp = root.join(format!("launch-chrome.sh.tmp-{}", uuid::Uuid::new_v4()));
    let mut content = format!(
        "#!/bin/bash\numask 077\nexport HOME={}\n",
        super::chrome::shell_quote(&crate::paths::app_home(&app.id).to_string_lossy())
    );
    if super::chrome::generated(app) {
        let resolved = super::chrome::resolve(app).map_err(String::from)?;
        content.push_str(&format!(
            "export TMPDIR={}\nmkdir -p -- {} {} \"$HOME\" \"$TMPDIR\"\n",
            super::chrome::shell_quote(&resolved.temp_dir.to_string_lossy()),
            super::chrome::shell_quote(&resolved.profile_dir.to_string_lossy()),
            super::chrome::shell_quote(&resolved.crash_dir.to_string_lossy())
        ));
    }
    content.push_str(command);
    content.push('\n');
    use std::os::unix::fs::OpenOptionsExt;
    let mut file = OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW)
        .open(&temp)
        .map_err(|e| e.to_string())?;
    use std::io::Write;
    file.write_all(content.as_bytes())
        .map_err(|e| e.to_string())?;
    fs::rename(&temp, &script).map_err(|e| e.to_string())?;
    let quoted = script
        .to_string_lossy()
        .replace('\\', "\\\\\\\\")
        .replace('"', "\\\"")
        .replace('`', "\\`")
        .replace('$', "\\$")
        .replace('%', "%%");
    let entries = base
        .map(PathBuf::from)
        .map(Ok)
        .unwrap_or_else(applications_dir)?;
    let path = entries.join(format!("ivnc-{}.desktop", app.id));
    write_entry(path, &app.name, &format!("/bin/bash \"{quoted}\""))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_the_known_legacy_builtin_entry_can_be_retired() {
        let command =
            super::super::api::builtin_chrome_command(Some("http://localhost:8080")).unwrap();
        let content = desktop_entry_content("Chrome", &command);
        assert!(known_legacy_chrome_entry(&content));
        assert!(!known_legacy_chrome_entry(&desktop_entry_content(
            "Custom Chrome",
            &command
        )));
        assert!(!known_legacy_chrome_entry(
            &content.replace("# Generated by iVnc", "# user entry")
        ));
        assert!(!known_legacy_chrome_entry(&desktop_entry_content(
            "Chrome",
            "my-browser --custom"
        )));
        assert!(!known_legacy_chrome_entry(
            &content.replace("--disable-dev-shm-usage", "--custom-flag")
        ));
    }
}
